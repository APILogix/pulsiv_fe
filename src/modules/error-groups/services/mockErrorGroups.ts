export function getMockErrorGroups(filters?: Partial<ErrorGroupFilterState>): ErrorGroup[] {
  let list = [...MOCK_ERROR_GROUPS];
  if (!filters) return list;

  if (filters.status) {
    list = list.filter((g) => g.status === filters.status);
  }
  if (filters.severity) {
    list = list.filter((g) => g.latestSeverity === filters.severity || g.highestSeverity === filters.severity);
  }
  if (filters.isRegression) {
    const isReg = filters.isRegression === "true";
    list = list.filter((g) => g.isRegression === isReg);
  }
  if (filters.environment) {
    list = list.filter((g) => g.environment === filters.environment);
  }
  if (filters.release) {
    list = list.filter((g) => g.latestRelease === filters.release);
  }
  if (filters.sdkVersion) {
    list = list.filter((g) => g.latestSdkVersion === filters.sdkVersion);
  }
  if (filters.appVersion) {
    list = list.filter((g) => g.latestApplicationVersion === filters.appVersion);
  }
  if (filters.search) {
    const q = filters.search.toLowerCase();
    list = list.filter(
      (g) =>
        g.lastErrorName.toLowerCase().includes(q) ||
        g.lastErrorMessage.toLowerCase().includes(q) ||
        g.service?.toLowerCase().includes(q) ||
        (g.route && g.route.toLowerCase().includes(q))
    );
  }
  return list;
}

